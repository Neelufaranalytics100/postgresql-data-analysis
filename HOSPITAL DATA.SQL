CREATE TABLE HOSPITAL_DATA (
	PATIENT_ID SERIAL PRIMARY KEY,
	AGE INT,
	GENDER VARCHAR(10),
	CONDITION VARCHAR(50),
	PROCEDURE VARCHAR(50),
	COST INT,
	LENGTH_OF_STAY INT,
	READMISSION VARCHAR(10),
	OUTCOME VARCHAR(50),
	SATISFACTION INT
);

SELECT
	*
FROM
	HOSPITAL_DATA
SELECT
	CONDITION,
	COUNT(*) AS PATIENT,
	ROUND(AVG(COST), 2) AS AVG_COST,
	SUM(COST) AS TOTAL_COST
FROM
	HOSPITAL_DATA
GROUP BY
	CONDITION
ORDER BY
	AVG_COST DESC;

